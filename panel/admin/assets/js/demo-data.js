A.importDemo = function () {
    if (!A.isMgr()) return A.toast("Only Super Admin / Manager can import demo data.");
    if (!confirm("Import demo categories, products, banners and coupons?")) return Promise.resolve();
    var D = A.DEMO, db = SUB.db, batch = db.batch();
    D.categories.forEach(function (c) { var id = c.id, x = Object.assign({}, c); delete x.id; batch.set(db.collection("categories").doc(id), x); });
    D.products.forEach(function (p, i) {
        var id = p.id, x = Object.assign({}, p); delete x.id;
        x.createdAt = firebase.firestore.Timestamp.fromMillis(Date.now() - i * 60000);
        batch.set(db.collection("products").doc(id), x);
    });
    D.banners.forEach(function (b, i) { batch.set(db.collection("banners").doc("demo-" + b.type + "-" + i), b); });
    D.coupons.forEach(function (c) { var id = c.code, x = Object.assign({}, c); delete x.code; batch.set(db.collection("discounts").doc(id), x); });
    return batch.commit().then(function () {
        A.toast("Demo data imported. Refreshing...");
        A.drop("products", "categories");
        setTimeout(function () { location.reload(); }, 900);
    }).catch(A.err);
};
